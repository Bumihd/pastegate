#!/usr/bin/env node
// Copies the names of the built-in detection rules from extension/locales/*.js
// into the dashboard (dashboard/src/locales/rules.generated.ts).
//
//   node scripts/sync-rule-names.mjs           rewrite the file
//   node scripts/sync-rule-names.mjs --check   exit 1 if the file is outdated (CI)

import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import vm from 'node:vm'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const localeDir = join(root, 'extension', 'locales')
const outFile = join(root, 'dashboard', 'src', 'locales', 'rules.generated.ts')
const check = process.argv.includes('--check')

const sandbox = { PG_LOCALES: {} }
sandbox.globalThis = sandbox
vm.createContext(sandbox)

const files = readdirSync(localeDir).filter(f => f.endsWith('.js')).sort()
for (const f of files) {
  const path = join(localeDir, f)
  vm.runInContext(readFileSync(path, 'utf8'), sandbox, { filename: path, timeout: 1000 })
}

const names = {}
for (const lang of Object.keys(sandbox.PG_LOCALES).sort()) {
  const rules = sandbox.PG_LOCALES[lang]?.rules
  if (!rules || typeof rules !== 'object') continue
  const map = {}
  for (const id of Object.keys(rules).sort()) {
    const name = rules[id]?.name
    if (typeof name === 'string' && name.trim()) map[id] = name
  }
  names[lang] = map
}

if (!Object.keys(names).length) {
  console.error(`no rule names found in ${relative(root, localeDir)}`)
  process.exit(2)
}

const q = s => JSON.stringify(s)
const ident = s => (/^[A-Za-z_$][\w$]*$/.test(s) ? s : q(s))
let out = '// generated by scripts/sync-rule-names.mjs — do not edit\n'
out += '// Source: extension/locales/*.js (rules.<id>.name). Regenerate: npm run sync-rules\n\n'
out += 'export const RULE_NAMES: Record<string, Record<string, string>> = {\n'
for (const [lang, map] of Object.entries(names)) {
  out += `  ${ident(lang)}: {\n`
  for (const [id, name] of Object.entries(map)) out += `    ${ident(id)}: ${q(name)},\n`
  out += '  },\n'
}
out += '}\n'

const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : null
const rel = relative(root, outFile)
if (check) {
  if (current !== out) {
    console.error(`${rel} is outdated – run "npm run sync-rules" in dashboard/`)
    process.exit(1)
  }
  console.log(`${rel} is up to date`)
} else if (current === out) {
  console.log(`${rel} unchanged`)
} else {
  writeFileSync(outFile, out)
  const counts = Object.entries(names).map(([l, m]) => `${l}: ${Object.keys(m).length}`).join(', ')
  console.log(`${rel} written (${counts})`)
}
